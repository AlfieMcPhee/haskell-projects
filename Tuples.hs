-- Tuples are like lists but, all tuples must have more than or 2 elements, can't have additional elements once initialised
-- Tuples must be of the same type

{- Tuple Functions
 fst takes a pair and returns the first component
 snd does the second
 zip takes two lists and loads them together into one list by joining the elements into 2 element tuples}
 ghci> zip [1 .. 5] ["one", "two", "three", "four", "five"]  
[(1,"one"),(2,"two"),(3,"three"),(4,"four"),(5,"five")] -}


